"""LaTeX tables and named values for the paper, from a frozen run.

    python paper/tables.py data/main/measures.jsonl > paper/results.tex

Uses the definitions in analysis.py, so every number in the paper is the
number in RESULTS.md. The prose cites values as \\val{key}; an unknown key
stops the LaTeX build instead of printing nothing.
"""

import json
import os
import statistics
import sys
from collections import defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from analysis import STATES, in_state, signals, wilson  # noqa: E402

ECOSYSTEMS = (("npm", "npm"), ("pypi", "PyPI"), ("go", "Go"))
STRATA = (("top", "Top"), ("tail", "Tail"))
SIGNALS = ("registry", "advisory", "lifecycle")
MEASURED = ("unchanged", "relocated", "unreachable")


def share(k, n):
    """`k/n` as a percentage with its Wilson interval, for a table cell."""
    if n == 0:
        return "--"
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def percent(k, n):
    return f"{100 * k / n:.1f}" if n else "n/a"


def main(path):
    rows = [json.loads(line) for line in open(path, encoding="utf-8")]
    groups = defaultdict(list)
    for row in rows:
        groups[(row["ecosystem"], row["stratum"])].append(row)
    values = {"N": f"{len(rows):,}"}
    out = [
        f"% Generated by paper/tables.py from {path}. Do not edit by hand.",
        r"\makeatletter",
        r"\newcommand{\val}[1]{\ifcsname val@#1\endcsname\csname val@#1\endcsname"
        r"\else\PackageError{results}{No value #1}{}\fi}",
    ]

    rq1 = [
        r"\begin{tabular}{llrrllll}",
        r"\toprule",
        r"Ecosystem & Stratum & Excl. & $n$ & Archived & Relocated & Unreachable & Any \\",
        r"\midrule",
    ]
    rq2 = [
        r"\begin{tabular}{llrrrrrrr}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{Archived} & \multicolumn{2}{c}{Relocated}"
        r" & \multicolumn{2}{c}{Unreachable} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
        r"Ecosystem & Stratum & $n$ & Median & Max & $n$ & Median & $n$ & Median \\",
        r"\midrule",
    ]
    rq3 = [
        r"\begin{tabular}{lllrllll}",
        r"\toprule",
        r"Ecosystem & Stratum & State & $n$ & Registry & Advisory & Lifecycle & Any \\",
        r"\midrule",
    ]
    rq4 = [
        r"\begin{tabular}{llrlr}",
        r"\toprule",
        r"Ecosystem & Stratum & Renamed & Stale published name & Relocated, no recorded rename \\",
        r"\midrule",
    ]
    other_max = 0

    for e, (eco, eco_name) in enumerate(ECOSYSTEMS):
        for stratum, stratum_name in STRATA:
            rs = groups[(eco, stratum)]
            key = f"{eco}-{stratum}"
            measured = [r for r in rs if r.get("repo_state") in MEASURED]
            n = len(measured)
            excluded = sum(r.get("repo_state") == "excluded" for r in rs)
            values[f"{key}-n"] = f"{n:,}"
            values[f"{key}-excluded"] = str(excluded)
            counts = {s: sum(in_state(r, s) for r in measured) for s in STATES}
            counts["any"] = sum(any(in_state(r, s) for s in STATES) for r in measured)
            for s, k in counts.items():
                values[f"{key}-{s}"] = percent(k, n)
            rq1.append(
                f"{eco_name} & {stratum_name} & {excluded} & {n:,} & "
                + " & ".join(share(counts[s], n) for s in (*STATES, "any"))
                + r" \\"
            )

            cells = []
            for s in STATES:
                hit = [r for r in rs if in_state(r, s)]
                deps = [r.get("dependent_repos_count") or 0 for r in hit]
                median = f"{statistics.median(deps):,.0f}" if deps else "--"
                values[f"{key}-{s}-median-repos"] = median
                cells += [str(len(hit)), median]
                if s == "archived":
                    cells.append(f"{max(deps):,}" if deps else "--")
            rq2.append(f"{eco_name} & {stratum_name} & " + " & ".join(cells) + r" \\")

            for s in ("archived", "unreachable"):
                hit = [r for r in rs if in_state(r, s)]
                sig = [signals(r) for r in hit]
                k = {name: sum(x[name] for x in sig) for name in SIGNALS}
                k["any"] = sum(any(x.values()) for x in sig)
                for name, count in k.items():
                    values[f"{key}-{s}-{name}"] = percent(count, len(hit))
                other_max = max(other_max, k["advisory"], k["lifecycle"])
                rq3.append(
                    f"{eco_name} & {stratum_name} & {s} & {len(hit)} & "
                    + " & ".join(share(k[name], len(hit)) for name in (*SIGNALS, "any"))
                    + r" \\"
                )

            linked = [r for r in rs if r.get("repo_state") in ("unchanged", "relocated")]
            renamed = [r for r in linked if r.get("frame_previous_names")]
            stale = sum(r.get("repo_state") == "relocated" for r in renamed)
            unrecorded = sum(
                r.get("repo_state") == "relocated" and not r.get("frame_previous_names")
                for r in linked
            )
            values[f"{key}-stale"] = percent(stale, len(renamed))
            rq4.append(
                f"{eco_name} & {stratum_name} & {len(renamed)} & "
                f"{share(stale, len(renamed))} & {unrecorded}" + r" \\"
            )

            archived = [r for r in rs if r.get("archived")]
            released = sum(
                1
                for r in archived
                if r.get("latest_released_at")
                and r.get("pushed_at")
                and r["latest_released_at"] > r["pushed_at"]
            )
            values[f"{key}-archived-released"] = percent(released, len(archived))
        if e < len(ECOSYSTEMS) - 1:
            for table in (rq1, rq2, rq3, rq4):
                table.append(r"\midrule")

    for table in (rq1, rq2, rq3, rq4):
        table += [r"\bottomrule", r"\end{tabular}"]

    # Groups are never pooled (PROTOCOL.md §3): the most packages any one
    # ecosystem and stratum had with an OSV or endoflife.date match.
    values["other-signal-max"] = str(other_max)

    agree = [
        r for r in rows if r.get("frame_archived") is not None and r.get("archived") is not None
    ]
    same = sum(bool(r["frame_archived"]) == bool(r["archived"]) for r in agree)
    values["frame-n"] = f"{len(agree):,}"
    values["frame-agree"] = share(same, len(agree))

    for name, value in sorted(values.items()):
        out.append(rf"\expandafter\def\csname val@{name}\endcsname{{{value}}}")
    out.append(r"\makeatother")
    for name, table in (("RQone", rq1), ("RQtwo", rq2), ("RQthree", rq3), ("RQfour", rq4)):
        out += [rf"\newcommand{{\table{name}}}{{%", *table, "}"]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
