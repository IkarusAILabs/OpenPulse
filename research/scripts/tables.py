# --- formatting ----------------------------------------------------------------


def _ci(interval: list[float] | None) -> str:
    return "n/a" if interval is None else f"[{interval[0]:.3f}, {interval[1]:.3f}]"


def _kn(block: dict[str, Any]) -> str:
    return f"{block['k']}/{block['n']}"


def _md(head: list[str], rows: list[list[str]], note: str = "") -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + (f"\n\n{note}" if note else "")


def _tex_escape(text: str) -> str:
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
    )


def _tex(
    head: list[str], rows: list[list[str]], caption: str, label: str, spec: str | None = None
) -> str:
    """A table scaled to the text width, or, with ``spec``, set at its own
    width with that column spec (for wrapped text columns)."""
    open_, close = (r"\resizebox{\linewidth}{!}{%", "}") if spec is None else ("", "")
    lines = [
        "% Generated by research/scripts/tables.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering\small",
        rf"\caption{{{_tex_escape(caption)}}}",
        rf"\label{{{label}}}",
        *([open_] if open_ else []),
        rf"\begin{{tabular}}{{{spec or 'l' + 'r' * (len(head) - 1)}}}",
        r"\toprule",
        " & ".join(_tex_escape(h) for h in head) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(_tex_escape(c) for c in r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}" + close, r"\end{table}"]
    return "\n".join(lines)


def _emit(name: str, head, rows, caption: str, note: str = "", spec: str | None = None) -> None:
    write_text(TABLES / f"{name}.md", f"**{caption}**\n\n" + _md(head, rows, note))
    write_text(TABLES / f"{name}.tex", _tex(head, rows, caption, f"tab:{name}", spec))


