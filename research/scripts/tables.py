def composition(dataset: str, evaluation: dict[str, Any]) -> None:
    pairs = [p for p in evaluation["pairs"] if p["policy"] == "C-openpulse"]
    classes = sorted({p["class"] for p in pairs})
    labels = ("in_scope", "out_of_scope", "undeterminable")
    rows = []
    for cls in classes:
        sub = [p for p in pairs if p["class"] == cls]
        count = Counter(p["label"] for p in sub)
        ident = Counter(p["identity"] for p in sub)
        rows.append(
            [
                cls,
                str(len({p["event"] for p in sub})),
                str(len(sub)),
                *(str(count[label]) for label in labels),
                *(str(ident[k]) for k in ("curated", "self", "heuristic")),
            ]
        )
    total = Counter(p["label"] for p in pairs)
    ident = Counter(p["identity"] for p in pairs)
    rows.append(
        [
            "total",
            str(len({p["event"] for p in pairs})),
            str(len(pairs)),
            *(str(total[label]) for label in labels),
            *(str(ident[k]) for k in ("curated", "self", "heuristic")),
        ]
    )
    head = [
        "event class",
        "events",
        "pairs",
        "in scope",
        "out of scope",
        "undeterminable",
        "identity curated",
        "identity self",
        "identity heuristic",
    ]
    _emit(
        f"{dataset}_composition",
        head,
        rows,
        f"Composition of {evaluation['dataset']} v{evaluation['dataset_version']} "
        "(labels are the developer's, L1; none is independent)",
        "Identity is how OpenPulse resolves the dependency: a curated mapping, the "
        "reference itself (unresolved), or a heuristic (REVIEW_REQUIRED).",
    )


def outcomes(dataset: str, evaluation: dict[str, Any], inference: dict[str, Any]) -> None:
    rows = []
    for group in ("registered", "post_hoc"):
        for policy in evaluation[group]:
            block = inference["policies"][policy]
            if "status" in block:
                rows.append([LABEL[policy], str(block["pairs"]), *["n/a"] * 7])
                continue
            enc = f" ({block['not_encoded']} not encoded)" if block["not_encoded"] else ""
            fc, fp = block["false_clear_rate"], block["false_positive_rate"]
            res, unres = block["resolution_rate"], block["unresolved_rate"]
            ev = block["events_with_false_clear"]
            rows.append(
                [
                    LABEL[policy] + enc,
                    str(block["pairs"] - block["not_encoded"]),
                    _kn(fc),
                    _ci(fc["clopper_pearson_95"]),
                    _kn(ev),
                    _kn(fp),
                    _kn(block["silent_miss_rate"]),
                    _kn(unres),
                    f"{_kn(res)} {_ci(res['event_bootstrap_95'])}",
                ]
            )
    head = [
        "policy",
        "pairs",
        "false clears / in scope",
        "95% CI (exact)",
        "events with a false clear",
        "false positives / out of scope",
        "silent misses / in scope",
        "unresolved / all",
        "resolved / determinable [event bootstrap 95%]",
    ]
    _emit(
        f"{dataset}_outcomes",
        head,
        rows,
        f"Decision outcomes on {evaluation['dataset']} by policy",
        "Exact intervals treat pairs as independent; the event bootstrap resamples "
        "events (pairs of one event move together). Post-hoc rows were defined after "
        "the registered results were known and are exploratory. n/a: the policy's "
        "representation encodes no event of this set.",
    )


def ablations(dataset: str, evaluation: dict[str, Any]) -> None:
    base = evaluation["registered"]["C-openpulse"]["categories"]
    keys = (
        "false_clear",
        "false_positive",
        "silent_miss",
        "unresolved",
        "correct_affected",
        "correct_unaffected",
    )
    rows = []
    variants = [k for k in evaluation["registered"] if k.startswith("C-ablate")] + list(POST_HOC)
    for policy in variants:
        group = "registered" if policy in evaluation["registered"] else "post_hoc"
        cats = evaluation[group][policy]["categories"]
        delta = [cats[k] - base[k] for k in keys]
        new = [k for k in ("false_clear", "false_positive", "silent_miss") if cats[k] > base[k]]
        rows.append(
            [
                LABEL[policy],
                *(f"{d:+d}" if d else "0" for d in delta),
                ", ".join(k.replace("_", " ") for k in new) or "none",
            ]
        )
    head = [
        "configuration (vs C)",
        "false clears",
        "false positives",
        "silent misses",
        "unresolved",
        "correct affected",
        "correct unaffected",
        "new failure modes",
    ]
    _emit(
        f"{dataset}_ablations",
        head,
        rows,
        f"Ablations on {evaluation['dataset']}: change in pair counts relative to C",
    )


def by_class(dataset: str, evaluation: dict[str, Any]) -> None:
    policies = ["A-naive", "C-posthoc-binary", "C-openpulse"]
    counts: dict[tuple[str, str], Counter] = defaultdict(Counter)
    for p in evaluation["pairs"]:
        if p["policy"] in policies:
            counts[(p["class"], p["policy"])][p["category"]] += 1
    classes = sorted({c for c, _ in counts})
    rows = []
    for cls in classes:
        row = [cls]
        for policy in policies:
            c = counts[(cls, policy)]
            row.append(f"{c['false_clear']} / {c['unresolved'] + c['abstained_undeterminable']}")
        rows.append(row)
    _emit(
        f"{dataset}_by_class",
        ["event class", *(f"{LABEL[p]}: false clears / unresolved" for p in policies)],
        rows,
        f"False clears and unresolved outcomes by event class ({evaluation['dataset']})",
    )


def versions(dataset: str, comparison: dict[str, Any]) -> None:
    rows = []
    for step in comparison["steps"]:
        rows.append(
            [
                f"{step['from']} -> {step['to']}",
                f"{step['changed']}/{step['pairs']}",
                "; ".join(f"{k}: {v}" for k, v in sorted(step["transitions"].items())) or "none",
                str(len(step["new_safety_errors"])),
                str(len(step["fixed_safety_errors"])),
            ]
        )
    _emit(
        f"{dataset}_versions",
        ["versions", "pairs changed", "transitions", "new safety errors", "fixed safety errors"],
        rows,
        f"{comparison['policy']} across implementation versions ({dataset}, same case file)",
    )


