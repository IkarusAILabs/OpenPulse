def conformance() -> None:
    matrix = load_json(CONFORMANCE / "matrix.json")
    randomized = load_json(CONFORMANCE / "randomized.json")
    mutation = load_json(CONFORMANCE / "mutation.json")
    invariants = load_json(CONFORMANCE / "invariants.json")
    sev = matrix["by_severity"]
    rows = [
        [
            "oracle matrix (exhaustive grid)",
            str(matrix["cases"]),
            ", ".join(f"{k}: {v}" for k, v in sorted(sev.items())),
        ],
        [
            f"randomised differential (seed {randomized['seed']})",
            str(randomized["cases"]),
            ", ".join(f"{k}: {v}" for k, v in sorted(randomized["summary_severity"].items())),
        ],
        [
            f"decision invariants I1-I8 (seeds {', '.join(map(str, invariants['seeds']))})",
            str(invariants["cases"]),
            f"violations: {sum(invariants['violations'].values())}; checks per invariant "
            + ", ".join(f"{k} {v}" for k, v in invariants["exercised"].items()),
        ],
        [
            "defect re-injection (mutants)",
            str(mutation["total"]),
            f"caught {mutation['caught']}; by invariants "
            f"{sum(1 for m in mutation['mutants'] if m.get('invariants'))}; not re-injected "
            + ", ".join(sorted(mutation["not_reinjected"])),
        ],
    ]
    _emit(
        "conformance",
        ["check", "cases", "result"],
        rows,
        "Conformance of the implementation to the specification",
        "The oracle and the invariants were written by the same team as the engine "
        "(THREATS_TO_VALIDITY.md); this is internal evidence, not formal verification.",
    )


