def per_event(dataset: str, evaluation: dict[str, Any]) -> None:
    policies = ("A-naive", "C-posthoc-binary", "C-openpulse")
    pairs: dict[str, dict[str, list[dict[str, Any]]]] = defaultdict(lambda: defaultdict(list))
    for p in evaluation["pairs"]:
        if p["policy"] in policies:
            pairs[p["event"]][p["policy"]].append(p)
    rows = []
    for event in sorted(pairs):
        c = Counter(p["category"] for p in pairs[event]["C-openpulse"])
        labels = Counter(p["label"] for p in pairs[event]["C-openpulse"])
        rows.append(
            [
                event,
                pairs[event]["C-openpulse"][0]["class"],
                str(len(pairs[event]["C-openpulse"])),
                str(labels["in_scope"]),
                *(
                    str(sum(1 for p in pairs[event][pol] if p["category"] == "false_clear"))
                    for pol in policies
                ),
                str(c["correct_affected"]),
                str(c["unresolved"] + c["abstained_undeterminable"]),
                str(c["correct_unaffected"] + c["no_association"]),
                str(c["false_positive"]),
            ]
        )
    _emit(
        f"{dataset}_events",
        [
            "event",
            "class",
            "pairs",
            "in scope",
            "A false clears",
            "C binary false clears",
            "C false clears",
            "C affected",
            "C unresolved",
            "C negatives",
            "C false positives",
        ],
        rows,
        f"Per-event outcomes ({evaluation['dataset']})",
        "C negatives are pairs C cleared or found no association for; only these can "
        "become false clears if a label changes.",
    )


def mutants() -> None:
    mutation = load_json(CONFORMANCE / "mutation.json")
    detectors = (
        ("matrix", "grid"),
        ("randomized", "random"),
        ("invariants", "invar."),
        ("version_differential", "version"),
        ("regression_tests", "tests"),
    )
    rows = [
        [m["mutant"], m["reintroduces"], *("yes" if m.get(k) else "-" for k, _ in detectors)]
        for m in mutation["mutants"]
    ]
    rows += [
        [name, f"not re-injected: {reason}", *("n/a" for _ in detectors)]
        for name, reason in sorted(mutation["not_reinjected"].items())
    ]
    _emit(
        "mutants",
        ["defect", "what the mutant re-introduces", *(label for _, label in detectors)],
        rows,
        "Known defects and disabled safety rules re-injected into the engine, "
        "and which check detects each",
        "Every mutant is a one-function patch of a defect the team already knew of, or a safety "
        "rule switched off; the campaign shows the checks catch regressions of known failures, "
        "not that they find unknown ones.",
        spec="l p{6.4cm} ccccc",
    )


