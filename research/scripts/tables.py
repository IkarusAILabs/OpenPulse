def outcome_figure(dataset: str, evaluation: dict[str, Any]) -> None:
    policies = [p for p in [*evaluation["registered"], *evaluation["post_hoc"]]]
    counts: dict[str, Counter] = {p: Counter() for p in policies}
    for pair in evaluation["pairs"]:
        if pair["category"] != "not_encoded":
            counts[pair["policy"]][GROUP[pair["category"]]] += 1
    policies = [p for p in policies if sum(counts[p].values())]
    left, width, bar, gap, top = 300, 560, 18, 10, 64
    height = top + len(policies) * (bar + gap) + 40
    total = max(sum(c.values()) for c in counts.values())
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {left + width + 30} {height}" '
        f'font-family="Helvetica, Arial, sans-serif" font-size="12" role="img" '
        f'aria-labelledby="t d">',
        f'<title id="t">Decision outcomes by policy, {evaluation["dataset"]}</title>',
        f'<desc id="d">Stacked pair counts per policy; the same counts are in '
        f"research/tables/{dataset}_outcomes.md.</desc>",
        f'<rect width="100%" height="100%" fill="{SURFACE}"/>',
    ]
    x = left
    for key, (color, name) in SERIES.items():  # legend, one row above the plot
        out.append(f'<rect x="{x}" y="14" width="10" height="10" rx="2" fill="{color}"/>')
        out.append(f'<text x="{x + 14}" y="23" fill="{INK2}">{name.split(" (")[0]}</text>')
        x += 14 + 7 * len(name.split(" (")[0]) + 18
    scale = width / total
    for tick in range(0, total + 1, 25):
        tx = left + tick * scale
        out.append(
            f'<line x1="{tx:.1f}" y1="{top - 6}" x2="{tx:.1f}" y2="{height - 34}" '
            f'stroke="{GRID}" stroke-width="1"/>'
        )
        out.append(
            f'<text x="{tx:.1f}" y="{height - 20}" fill="{INK2}" text-anchor="middle">{tick}</text>'
        )
    out.append(
        f'<text x="{left + width / 2}" y="{height - 4}" fill="{INK2}" '
        f'text-anchor="middle">pairs</text>'
    )
    for i, policy in enumerate(policies):
        y = top + i * (bar + gap)
        out.append(
            f'<text x="{left - 8}" y="{y + 13}" fill="{INK}" text-anchor="end">'
            f"{LABEL[policy]}</text>"
        )
        x = left
        for key, (color, name) in SERIES.items():
            n = counts[policy][key]
            if not n:
                continue
            w = n * scale
            out.append(
                f'<rect x="{x:.1f}" y="{y}" width="{max(w - 2, 0.5):.1f}" height="{bar}" '
                f'rx="2" fill="{color}"><title>{LABEL[policy]}: {name} {n}</title></rect>'
            )
            if w > 24:
                out.append(
                    f'<text x="{x + w / 2 - 1:.1f}" y="{y + 13}" fill="{INK}" '
                    f'text-anchor="middle" font-size="11">{n}</text>'
                )
            x += w
    out.append("</svg>")
    write_text(FIGURES / f"{dataset}_outcomes.svg", "\n".join(out))
    _outcome_tikz(dataset, policies, counts, total)


def _outcome_tikz(dataset: str, policies: list[str], counts: dict, total: int) -> None:
    """The same bars as TikZ, for the manuscript (LaTeX cannot read SVG)."""
    unit = 9.0 / total  # cm per pair
    out = [
        "% Generated by research/scripts/tables.py -- do not edit by hand.",
        r"\begin{tikzpicture}[font=\scriptsize]",
    ]
    for key, (color, _) in SERIES.items():
        out.append(rf"\definecolor{{op{key.replace('_', '')}}}{{HTML}}{{{color[1:].upper()}}}")
    for i, policy in enumerate(policies):
        y = -0.5 * i
        out.append(rf"\node[anchor=east] at (-0.1,{y:.2f}) {{{_tex_escape(LABEL[policy])}}};")
        x = 0.0
        for key in SERIES:
            n = counts[policy][key]
            if not n:
                continue
            w = n * unit
            name = key.replace("_", "")
            out.append(
                rf"\fill[op{name}] ({x:.3f},{y - 0.17:.2f}) rectangle "
                rf"({x + w - 0.03:.3f},{y + 0.17:.2f});"
            )
            if w > 0.45:
                out.append(rf"\node at ({x + w / 2:.3f},{y:.2f}) {{{n}}};")
            x += w
    bottom = -0.5 * len(policies)
    for tick in range(0, total + 1, 25):
        out.append(
            rf"\draw[gray] ({tick * unit:.3f},{bottom + 0.15:.2f}) -- ++(0,-0.08) "
            rf"node[below] {{{tick}}};"
        )
    legend_y = bottom - 0.75
    x = 0.0
    for key, (_, label) in SERIES.items():
        short = label.split(" (")[0]
        name = key.replace("_", "")
        out.append(rf"\fill[op{name}] ({x:.2f},{legend_y:.2f}) rectangle ++(0.25,0.25);")
        out.append(rf"\node[anchor=west] at ({x + 0.3:.2f},{legend_y + 0.12:.2f}) {{{short}}};")
        x += 0.55 + 0.13 * len(short)
    out.append(r"\end{tikzpicture}")
    write_text(FIGURES / f"{dataset}_outcomes.tex", "\n".join(out))


def _label_numbers(sens: dict[str, Any]) -> dict[str, Any]:
    """Macros for the label-sensitivity paragraph (AI_PANEL_PROTOCOL.md §6)."""
    agree, res = sens["agreement"], sens["rescored"]

    def kappa(name: str) -> str:
        return f"{agree[name]['kappa']:.2f}"

    def ci(name: str) -> str:
        low, high = agree[name]["kappa_event_bootstrap_95"]
        return f"[{low:.2f}, {high:.2f}]"

    def fc(label_set: str, policy: str) -> int:
        return res[label_set][policy]["false_clears"]

    def fc_events(label_set: str, policy: str) -> int:
        return res[label_set][policy]["events_with_false_clear"]

    ab, apl1 = agree["AI-A vs AI-B"], agree["AI-AP vs L1"]
    values = {
        "LabAgreeAB": ab["agree"],
        "LabKappaAB": kappa("AI-A vs AI-B"),
        "LabKappaABci": ci("AI-A vs AI-B"),
        "LabAdjudicated": ab["pairs"] - ab["agree"],
        "LabAgreeAPLone": apl1["agree"],
        "LabKappaAPLone": kappa("AI-AP vs L1"),
        "LabKappaAPLoneci": ci("AI-AP vs L1"),
        "LabDisagreeAPLone": sens["disagreements_L1_vs_AP"]["count"],
        "LabInAP": res["AI-AP"]["C-openpulse"]["in_scope"],
        "LabUndAP": res["AI-AP"]["C-openpulse"]["undeterminable"],
        "LabDecidedToUnd": sum(
            1
            for p in sens["disagreements_L1_vs_AP"]["pairs"]
            if p["AI-AP"] == "undeterminable" and p["L1"] != "undeterminable"
        ),
        "LabAtRiskAP": res["AI-AP"]["C-openpulse"]["events_at_risk"],
    }
    for label_set, macro in (
        ("AI-A", "A"),
        ("AI-B", "B"),
        ("AI-AP", "AP"),
        ("bound against C", "BoundC"),
        ("bound against A", "BoundA"),
    ):
        values[f"LabFCc{macro}"] = fc(label_set, "C-openpulse")
        values[f"LabFCcEv{macro}"] = fc_events(label_set, "C-openpulse")
        values[f"LabFCa{macro}"] = fc(label_set, "A-naive")
        values[f"LabFCaEv{macro}"] = fc_events(label_set, "A-naive")
        values[f"LabFCbin{macro}"] = fc(label_set, "C-posthoc-binary")
    return values


def numbers() -> None:
    """LaTeX macros for every number the manuscript's prose cites.

    The prose uses ``\\Name{}`` macros from numbers.tex, never literals, so
    the text cannot drift from the results and ``reproduce.py --check``
    covers it.
    """
    ev = load_json(RESULTS / "retro" / "evaluation.json")
    inf = load_json(RESULTS / "retro" / "inference.json")
    pol = inf["policies"]
    cat = {**ev["registered"], **ev["post_hoc"]}
    mutation = load_json(CONFORMANCE / "mutation.json")
    invariants = load_json(CONFORMANCE / "invariants.json")
    matrix = load_json(CONFORMANCE / "matrix.json")
    randomized = load_json(CONFORMANCE / "randomized.json")
    c = pol["C-openpulse"]
    at_risk = c["events_with_false_clear"]["n"]

    def k(policy: str, metric: str) -> int:
        return pol[policy][metric]["k"]

    def n_cat(policy: str, name: str) -> int:
        return cat[policy]["categories"][name]

    base = cat["C-openpulse"]["categories"]
    faults = load_json(RESULTS / "retro" / "identity_faults.json")["summary"]
    c_pairs = [p for p in ev["pairs"] if p["policy"] == "C-openpulse"]
    negatives = [p for p in c_pairs if p["category"] in ("correct_unaffected", "no_association")]
    identity = Counter(p["identity"] for p in c_pairs)
    misattributed = faults["misattributed"]["after"]
    values = {
        "RetroEvents": len({p["event"] for p in ev["pairs"] if p["policy"] == "C-openpulse"}),
        "RetroPairs": c["pairs"],
        "RetroInScope": c["false_clear_rate"]["n"],
        "RetroOutScope": c["false_positive_rate"]["n"],
        "RetroDeterminable": c["resolution_rate"]["n"],
        "EventsAtRisk": at_risk,
        "FCa": k("A-naive", "false_clear_rate"),
        "FCaEvents": pol["A-naive"]["events_with_false_clear"]["k"],
        "FCc": k("C-openpulse", "false_clear_rate"),
        "FCcUpper": f"{c['false_clear_rate']['clopper_pearson_95'][1]:.3f}",
        "FCcEventUpper": f"{1 - 0.05 ** (1 / at_risk):.3f}",
        "FCbinary": k("C-posthoc-binary", "false_clear_rate"),
        "FCbinaryEvents": pol["C-posthoc-binary"]["events_with_false_clear"]["k"],
        "SignAp": f"{inf['paired_with_C']['A-naive']['sign_test_one_sided_p']:.4f}",
        "SignBinaryp": f"{inf['paired_with_C']['C-posthoc-binary']['sign_test_one_sided_p']:.4f}",
        "UnresA": k("A-naive", "unresolved_rate"),
        "UnresB": k("B-conservative", "unresolved_rate"),
        "UnresV": k("V-strong-conservative", "unresolved_rate"),
        "UnresC": k("C-openpulse", "unresolved_rate"),
        "ResA": k("A-naive", "resolution_rate"),
        "ResB": k("B-conservative", "resolution_rate"),
        "ResV": k("V-strong-conservative", "resolution_rate"),
        "ResC": k("C-openpulse", "resolution_rate"),
        "FPa": k("A-naive", "false_positive_rate"),
        "FPc": k("C-openpulse", "false_positive_rate"),
        "ComplChanged": n_cat("C-ablate-completeness", "correct_unaffected")
        - base["correct_unaffected"],
        "IdAblMiss": n_cat("C-ablate-identity", "silent_miss"),
        "NameIdMiss": n_cat("C-posthoc-name-identity", "silent_miss"),
        "NoCurAffectedDrop": base["correct_affected"]
        - n_cat("C-posthoc-no-curated-identity", "correct_affected"),
        "NoCurUnresRise": n_cat("C-posthoc-no-curated-identity", "unresolved") - base["unresolved"],
        "PairsPerEvent": inf["clusters"]["mean_pairs_per_event"],
        "MatrixCases": f"{matrix['cases']:,}",
        "RandCases": f"{randomized['cases']:,}",
        "InvCases": f"{invariants['cases']:,}",
        "InvViolations": sum(invariants["violations"].values()),
        "MutCaught": mutation["caught"],
        "MutTotal": mutation["total"],
        "MutByInv": sum(1 for m in mutation["mutants"] if m.get("invariants")),
        "MutNotReinjected": len(mutation["not_reinjected"]),
        "MutKnown": mutation["total"] + len(mutation["not_reinjected"]),
        "FCaBoot": _ci(pol["A-naive"]["false_clear_rate"]["event_bootstrap_95"]),
        "BootResamples": f"{inf['bootstrap']['resamples']:,}",
        "BootSeed": inf["bootstrap"]["seed"],
        "NegC": len(negatives),
        "NegCEvents": len({p["event"] for p in negatives}),
        "NegCInScope": sum(1 for p in negatives if p["label"] == "in_scope"),
        "NegCOther": len(c_pairs) - len(negatives),
        "IdCurated": identity["curated"],
        "IdSelf": identity["self"],
        "IdHeuristic": identity["heuristic"],
        "FaultMis": faults["misattributed"]["injected"],
        "FaultMisMiss": misattributed.get("silent_miss", 0),
        "FaultMisNoAssoc": misattributed.get("no_association", 0),
        "FaultMisInScope": sum(
            1 for p in c_pairs if p["identity"] == "curated" and p["label"] == "in_scope"
        ),
        "FaultCol": faults["collided"]["injected"],
        "FaultColChanged": faults["collided"]["changed"],
        "FaultColFP": faults["collided"]["after"].get("false_positive", 0),
        **_label_numbers(load_json(RESULTS / "retro" / "label_sensitivity.json")),
    }
    lines = ["% Generated by research/scripts/tables.py -- do not edit by hand."]
    lines += [rf"\newcommand{{\{name}}}{{{value}}}" for name, value in values.items()]
    write_text(TABLES / "numbers.tex", "\n".join(lines))


