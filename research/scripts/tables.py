def label_agreement(sensitivity: dict[str, Any]) -> None:
    rows = []
    for name, block in sensitivity["agreement"].items():
        ci = block["kappa_event_bootstrap_95"]
        rows.append(
            [
                name,
                str(block["pairs"]),
                f"{block['agree']}/{block['pairs']}",
                "n/a" if block["kappa"] is None else f"{block['kappa']:.3f}",
                "n/a" if ci is None else f"[{ci[0]:.3f}, {ci[1]:.3f}]",
            ]
        )
    _emit(
        "retro_label_agreement",
        ["label sets", "pairs", "agree", "Cohen's kappa", "95% CI (event bootstrap)"],
        rows,
        f"Agreement between labelling methods ({sensitivity['dataset']})",
        "Every set except L1 is AI-generated (AI_PANEL_PROTOCOL.md); agreement between two "
        "models measures their consistency, not the labels' validity. The pilot rounds "
        "cover a 25% sample.",
    )


