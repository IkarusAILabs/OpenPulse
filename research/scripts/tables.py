# --- formatting ----------------------------------------------------------------


def _ci(interval: list[float] | None) -> str:
    return "n/a" if interval is None else f"[{interval[0]:.3f}, {interval[1]:.3f}]"


def _kn(block: dict[str, Any]) -> str:
    return f"{block['k']}/{block['n']}"


def _md(head: list[str], rows: list[list[str]], note: str = "") -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + (f"\n\n{note}" if note else "")


def _tex_escape(text: str) -> str:
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
    )


def _tex(head: list[str], rows: list[list[str]], caption: str, label: str) -> str:
    spec = "l" + "r" * (len(head) - 1)
    lines = [
        "% Generated by research/scripts/tables.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering\small",
        rf"\caption{{{_tex_escape(caption)}}}",
        rf"\label{{{label}}}",
        r"\resizebox{\linewidth}{!}{%",
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
        " & ".join(_tex_escape(h) for h in head) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(_tex_escape(c) for c in r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    return "\n".join(lines)


def _emit(name: str, head, rows, caption: str, note: str = "") -> None:
    write_text(TABLES / f"{name}.md", f"**{caption}**\n\n" + _md(head, rows, note))
    write_text(TABLES / f"{name}.tex", _tex(head, rows, caption, f"tab:{name}"))


