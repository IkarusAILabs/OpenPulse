"""Regenerate the hash-pinned lock files (maintainer tool; needs `uv`).

    python scripts/compile_locks.py            # re-hash, keep every current pin
    python scripts/compile_locks.py --upgrade  # re-resolve to the newest allowed

Writes five files, all with `--hash` entries for every distribution file
of every pinned version, resolved universally (Linux, macOS, Windows):

- requirements.lock          - core + `dev` extra, Python >= 3.10;
- requirements-runtime.lock  - core runtime only (no dev tools), the same pins;
  the GitHub Action installs it (`--require-hashes`, then `--no-deps -e .`);
- requirements-mcp.lock      - only what the `mcp` extra adds on top, Python
  >= 3.11 (MCP SDK 2.x requires 3.11+);
- .github/ci-tools.lock      - the pip/setuptools CI bootstraps with (`CI_TOOLS`);
- .github/audit-tools.lock   - pip-audit and its dependencies (`AUDIT_TOOLS`),
  constrained to the core lock so installing it never moves a project pin.

CI installs them with `pip install --require-hashes`, so a re-uploaded
or tampered artifact with the same version fails the install, and every
transitive dependency must be listed (an unlisted one fails too).
Without `--upgrade`, current pins are passed as constraints so nothing
floats; review the diff, then commit both files together.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "requirements.lock"
MCP = ROOT / "requirements-mcp.lock"
RUNTIME = ROOT / "requirements-runtime.lock"
CI_TOOLS_LOCK = ROOT / ".github" / "ci-tools.lock"
AUDIT_TOOLS_LOCK = ROOT / ".github" / "audit-tools.lock"
#: CI tooling versions - bump here, then rerun this script.
CI_TOOLS = ("pip==26.2.1", "setuptools==84.2.1")
AUDIT_TOOLS = ("pip-audit==2.10.1",)
_ENTRY = re.compile(r"^([A-Za-z0-9_.\-]+)==")

CORE_HEADER = """\
# OpenPulse lock: core + dev extra, hash-pinned (Python >= 3.10, all platforms).
# Generated by scripts/compile_locks.py - do not edit by hand.
# CI: pip install --require-hashes -r requirements.lock && pip install --no-deps -e .
"""
RUNTIME_HEADER = """\
# OpenPulse lock: runtime dependencies only (no dev tools), hash-pinned, same pins
# as requirements.lock. Generated by scripts/compile_locks.py - do not edit by hand.
# GitHub Action: pip install --require-hashes -r requirements-runtime.lock
#                && pip install --no-deps -e <action root>
"""
MCP_HEADER = """\
# OpenPulse lock: what the optional `mcp` extra adds on top of requirements.lock,
# hash-pinned (Python >= 3.11: MCP SDK 2.x requires it).
# Generated by scripts/compile_locks.py - do not edit by hand.
# CI (mcp job): pip install --require-hashes -r requirements.lock -r requirements-mcp.lock
"""


def _pins(path: Path) -> list[str]:
    """`name==version` lines of an existing lock (markers and hashes dropped)."""
    if not path.exists():
        return []
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if _ENTRY.match(line):
            out.append(line.split(";")[0].split("\\")[0].strip())
    return out


def _compile(
    uv: str,
    source: Path,
    python: str,
    constraints: Path | None,
    extras: tuple[str, ...] = (),
) -> str:
    cmd = [uv, "pip", "compile", str(source), "--universal",
           "--python-version", python, "--generate-hashes", "--no-header", "--no-annotate",
           "--quiet"]
    for extra in extras:
        cmd += ["--extra", extra]
    if constraints is not None:
        cmd += ["-c", str(constraints)]
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def _tool_lock(uv: str, tmp: str, name: str, pins: tuple[str, ...], core: Path | None) -> str:
    source = Path(tmp) / f"{name}.in"
    source.write_text("\n".join(pins) + "\n", encoding="utf-8")
    return _compile(uv, source, "3.11", core)


def _blocks(compiled: str) -> dict[str, str]:
    """name -> its full entry (the pin line plus its `--hash` continuation lines)."""
    blocks: dict[str, str] = {}
    current = None
    for line in compiled.splitlines():
        match = _ENTRY.match(line)
        if match:
            current = match.group(1).lower()
            blocks[current] = line
        elif current and line.startswith(" "):
            blocks[current] += "\n" + line
    return blocks


def main(argv: list[str]) -> int:
    uv = shutil.which("uv")
    if uv is None:
        print("compile_locks: needs `uv` on PATH (pip install uv)", file=sys.stderr)
        return 2
    upgrade = "--upgrade" in argv
    with tempfile.TemporaryDirectory() as tmp:
        pins = None
        if not upgrade:
            pins = Path(tmp) / "pins.txt"
            pins.write_text("\n".join(_pins(CORE) + _pins(MCP)) + "\n", encoding="utf-8")
        pyproject = ROOT / "pyproject.toml"
        core = _blocks(_compile(uv, pyproject, "3.10", pins, ("dev",)))
        full = _blocks(_compile(uv, pyproject, "3.11", pins, ("dev", "mcp")))
        mcp_only = {name: block for name, block in full.items() if name not in core}
        runtime = _blocks(_compile(uv, pyproject, "3.10", pins))
        assert set(runtime) <= set(core), "runtime lock must be a subset of the core lock"
        CORE.write_text(CORE_HEADER + "\n".join(core.values()) + "\n", encoding="utf-8")
        RUNTIME.write_text(RUNTIME_HEADER + "\n".join(runtime.values()) + "\n", encoding="utf-8")
        MCP.write_text(MCP_HEADER + "\n".join(mcp_only.values()) + "\n", encoding="utf-8")
        # Tools: audit constrained to the freshly written core pins and the
        # bootstrap pins, so installing pip-audit moves neither.
        core_pins = Path(tmp) / "core-pins.txt"
        core_pins.write_text("\n".join(_pins(CORE) + list(CI_TOOLS)) + "\n", encoding="utf-8")
        tools = _tool_lock(uv, tmp, "ci-tools", CI_TOOLS, None)
        audit = _tool_lock(uv, tmp, "audit-tools", AUDIT_TOOLS, core_pins)
    CI_TOOLS_LOCK.write_text(
        "# CI bootstrap (pip, setuptools), hash-pinned. Generated by scripts/compile_locks.py.\n"
        + tools, encoding="utf-8")
    AUDIT_TOOLS_LOCK.write_text(
        "# pip-audit + dependencies, hash-pinned, constrained to requirements.lock.\n"
        "# Generated by scripts/compile_locks.py.\n" + audit, encoding="utf-8")
    print(
        f"wrote {CORE.name} ({len(core)} pins), {RUNTIME.name} ({len(runtime)} pins), "
        f"{MCP.name} ({len(mcp_only)} pins), "
        f"{CI_TOOLS_LOCK.name}, {AUDIT_TOOLS_LOCK.name}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
